""" Correlations that survive storing and loading values """
import unittest
from mongoengine import disconnect
from bgexplorer.models.asymmetric import AsymmetricUncertainty
from bgexplorer.models.component import Component
from bgexplorer.models.cosmogenic import (ActivatedMaterial,
                                          CosmogenicActivation,
                                          ActivationPeriod)
from bgexplorer.models.emissionspec import EmissionSpec, EmissionSource
from bgexplorer.models.hiteff import HitEfficiency
from bgexplorer.models.settings import VersionSettings
from bgexplorer.models.sourceterm import SourceTerm, clear_results_cache
from bgexplorer.models.common import units
from bgexplorer.models import versioncontrol as vc
from tests.dbutil import connect_test_db
from tests.test_cosmogenic import copper


def total(quantities):
    result = None
    for q in quantities:
        result = q if result is None else result + q
    return result


class TestStoredCorrelations(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        connect_test_db()

    @classmethod
    def tearDownClass(cls):
        disconnect()

    def setUp(self):
        for cls in (VersionSettings, Component, EmissionSpec, SourceTerm,
                    HitEfficiency, ActivatedMaterial):
            cls.drop_collection()
        clear_results_cache()
        vc.create_version('main')

    def test_computed_rate(self):
        """ a rate computed from a variable is stored with it """
        x = AsymmetricUncertainty(10, 1) * units('mBq/kg')
        spec = EmissionSpec(name='e', sources=[
            EmissionSource(name='K40', rate=x * 2),
            EmissionSource(name='Co60', rate=x * 3)]).save()
        spec = EmissionSpec.objects.get(id=spec.id)
        a, b = (s.rate for s in spec.sources)
        self.assertFalse(a.m.isleaf)
        self.assertAlmostEqual((a + b).to('mBq/kg').m.s0, 5)
        self.assertAlmostEqual((a - 2 * x).to('mBq/kg').m.s0, 0)

    def test_generated_sources(self):
        """ sources generated by the settings are correlated with theirs """
        settings = VersionSettings.objects.get(version_tag='main')
        self.assertIn('Ra226', [a.newsource for a in settings.addsources])
        spec = EmissionSpec(name='e', sources=dict(
            U238='10 +- 1 mBq/kg')).save()
        spec = EmissionSpec.objects.get(id=spec.id)
        rates = {s.name: s.rate for s in spec.sources}
        # Ra226 is in equilibrium with U238, so their errors add linearly
        self.assertAlmostEqual(
            (rates['U238'] + rates['Ra226']).to('mBq/kg').m.s0, 2)
        # as does U235, from its natural abundance
        u238, u235 = (rates[n].to('mBq/kg').m for n in ('U238', 'U235'))
        self.assertAlmostEqual((u238 + u235).s0, u238.s0 + u235.s0)

    def test_activations_of_one_material(self):
        """ activations of the same material are correlated through its
        activation rates
        """
        cu = copper().save()
        specs = [CosmogenicActivation(name=f'Cu {days} d', material=cu,
                                      periods=[ActivationPeriod(
                                          duration=f'{days} day')]).save()
                 for days in (100, 200)]
        for i, spec in enumerate(specs):
            Component(name=f'c{i}', mass='1 kg', specs=[spec]).save()

        def co60():
            return [st.emissionrate for st in SourceTerm.objects(
                source__name='Co60')]
        rates = co60()
        self.assertEqual(len(rates), 2)
        expected = sum(r.to('Bq').m.s0 for r in rates)
        independent = sum(r.to('Bq').m.s0**2 for r in rates) ** 0.5
        self.assertGreater(expected, 1.2 * independent)
        self.assertAlmostEqual(total(rates).to('Bq').m.s0, expected)
        # including after loading the specs again and recalculating
        for spec in CosmogenicActivation.objects:
            spec.save()
        self.assertAlmostEqual(total(co60()).to('Bq').m.s0, expected)


if __name__ == '__main__':
    unittest.main()
